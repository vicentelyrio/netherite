// Writes the reference pages in apps/docs/reference/ from the program itself: the CLI's own help, the
// MCP server's tool and resource listings, and the item types' JSON Schemas; and apps/docs/templates.md
// from the starter templates that ship. They are generated
// so they cannot drift from the code. `--check` writes nothing and exits 1 if a page is stale.
// Needs a build: run `pnpm build` first.
import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'apps/docs/reference')
const bin = join(root, 'packages/cli/dist/bin.mjs')
const check = process.argv.includes('--check')
const require = createRequire(join(root, 'packages/mcp/package.json'))

const header = (title, intro) =>
  `<!-- Generated by \`pnpm docs:gen\` from the program. Do not edit by hand. -->\n\n# ${title}\n\n${intro}\n\n`

// ---- CLI ------------------------------------------------------------------------------------

const help = (...args) =>
  execFileSync('node', [bin, ...args, '--help'], { encoding: 'utf8' })
    // The global flags are the same for every command: they are listed once, at the top.
    .replace(/\nGLOBAL FLAGS[\s\S]*$/, '')
    .trimEnd()

const commands = [
  [[], 'netherite'],
  [['serve'], 'netherite serve'],
  [['init'], 'netherite init'],
  [['new'], 'netherite new'],
  [['templates'], 'netherite templates'],
  [['scan'], 'netherite scan'],
  [['import'], 'netherite import'],
  [['lint'], 'netherite lint'],
  [['renumber'], 'netherite renumber'],
  [['mcp'], 'netherite mcp'],
  [['context', 'sync'], 'netherite context sync'],
  [['timeline'], 'netherite timeline'],
  [['stats'], 'netherite stats'],
]

const cli = () => {
  let text = header(
    'CLI reference',
    'Every command and flag. Run `netherite <command> --help` for the same text. Exit codes: **0** success, **1** the request was understood but there are problems (lint findings, a refused write), **2** it could not run at all (no workspace, bad config).',
  )
  text +=
    'Every command takes `--help`, `--version`, `--log-level <level>` and `--completions <shell>`. With no command, `netherite` runs `serve`.\n\n'
  for (const [args, title] of commands) {
    text += `## \`${title}\`\n\n\`\`\`text\n${help(...args)}\n\`\`\`\n\n`
  }
  return text
}

// ---- templates ------------------------------------------------------------------------------

const templatesPage = async () => {
  const { templates, templateTypes } = await import(join(root, 'packages/core/dist/index.mjs'))
  let text = `<!-- Generated by \`pnpm docs:gen\` from the program. Do not edit by hand. -->

# Templates

Each item type has a starter template: the frontmatter with every optional field in a comment, and
the sections the app and \`netherite lint\` expect. Optional fields start with \`#\`; remove the
\`#\` to use one. <code v-pre>{{name}}</code> marks a value that Netherite fills in.

## Use them

\`\`\`sh
netherite new adr "Use GNU Stow" --template     # the item starts with the template's sections
netherite templates                             # list the types and where each template comes from
netherite templates task                        # print one, to copy into your own file
\`\`\`

\`--body\` and \`--body-file\` replace the template's text. \`new\` writes the frontmatter itself, with the
fields you give it; the template supplies the sections.

## Make them your own

Put a file called \`<type>.md\` in \`templates/\` inside the content folder (\`netherite/templates/adr.md\`
by default). It replaces the built-in template for that type in this workspace. Start from the text
below. Files in \`templates/\` are not items: they are not indexed and are not linted as items. If one
names a frontmatter field the type does not have, \`netherite lint\` reports \`template-unknown-field\`.

`
  for (const type of templateTypes) {
    text += `## ${type}\n\n\`\`\`markdown\n${templates[type].trimEnd()}\n\`\`\`\n\n`
  }
  return text
}

// ---- MCP + schemas --------------------------------------------------------------------------

const { Client } = require('@modelcontextprotocol/sdk/client/index.js')
const { StdioClientTransport } = require('@modelcontextprotocol/sdk/client/stdio.js')

const typeOf = (schema) => {
  if (schema.enum) return schema.enum.map((v) => `\`${v}\``).join(' \\| ')
  if (schema.anyOf) return schema.anyOf.map(typeOf).join(' \\| ')
  if (schema.type === 'array') return `${schema.items ? typeOf(schema.items) : 'any'}[]`
  return schema.type ?? 'any'
}

const table = (schema) => {
  const props = Object.entries(schema.properties ?? {})
  if (props.length === 0) return '_No inputs._\n'
  const required = new Set(schema.required ?? [])
  const oneLine = (s) =>
    String(s ?? '')
      .replace(/\s+/g, ' ')
      .replace(/\|/g, '\\|')
  return (
    '| Name | Type | Required | Description |\n| --- | --- | --- | --- |\n' +
    props
      .map(
        ([name, s]) =>
          `| \`${name}\` | ${typeOf(s)} | ${required.has(name) ? 'yes' : ''} | ${oneLine(s.description)} |`,
      )
      .join('\n') +
    '\n'
  )
}

const mcpAndSchemas = async () => {
  const client = new Client({ name: 'docs', version: '0.0.0' })
  await client.connect(
    new StdioClientTransport({
      command: 'node',
      args: [bin, 'mcp', '--no-watch', '-C', root],
      stderr: 'pipe',
    }),
  )
  const { tools } = await client.listTools()
  const { resources } = await client.listResources()
  const { resourceTemplates } = await client.listResourceTemplates()
  const types = resources
    .filter((r) => r.uri.startsWith('netherite://schema/'))
    .map((r) => r.uri.split('/').at(-1))
  const schemas = {}
  for (const type of types) {
    const read = await client.readResource({ uri: `netherite://schema/${type}` })
    schemas[type] = JSON.parse(read.contents[0].text)
  }
  await client.close()

  let mcp = header(
    'MCP reference',
    'What `netherite mcp` (stdio) and `/mcp` on a running `netherite serve` (streamable HTTP) offer an agent. Every write returns the new `hash`; pass it back as `baseHash` and the write fails if the file changed in between.',
  )
  mcp += '## Tools\n\n'
  for (const tool of tools) {
    mcp += `### \`${tool.name}\`\n\n${tool.description}\n\n${table(tool.inputSchema)}\n`
  }
  mcp += '## Resources\n\n| URI | What |\n| --- | --- |\n'
  for (const r of resources.filter((r) => !r.uri.startsWith('netherite://schema/'))) {
    mcp += `| \`${r.uri}\` | ${r.description} |\n`
  }
  for (const t of resourceTemplates) mcp += `| \`${t.uriTemplate}\` | ${t.description} |\n`
  mcp += `\nThe schema of each item type is read at \`netherite://schema/<type>\` (${types.join(', ')}); see the [schema reference](schemas.md).\n`

  let sch = header(
    'Item schemas',
    'The fields of each item type, as the validator checks them (`netherite lint`, and every write). IDs look like `TASK-00042`, and a field that links to another item holds its ID. Unknown fields are kept and ignored. The same JSON Schemas are served at `netherite://schema/<type>` and `GET /api/schemas/<type>`.',
  )
  for (const type of types) {
    const s = schemas[type]
    sch += `## \`${type}\`\n\n`
    const required = new Set(s.required ?? [])
    const rows = Object.entries(s.properties ?? {}).map(([name, p]) => {
      const desc = [
        p.description,
        p.pattern ? `pattern \`${p.pattern}\`` : '',
        p.format ? `format ${p.format}` : '',
      ]
        .filter(Boolean)
        .join('; ')
      return `| \`${name}\` | ${typeOf(p)} | ${required.has(name) ? 'yes' : ''} | ${String(desc).replace(/\|/g, '\\|')} |`
    })
    sch += `| Field | Type | Required | Notes |\n| --- | --- | --- | --- |\n${rows.join('\n')}\n\n`
  }
  return { mcp, schemas: sch }
}

const pages = async () => {
  const { mcp, schemas } = await mcpAndSchemas()
  return {
    'cli.md': cli(),
    'mcp.md': mcp,
    'schemas.md': schemas,
    '../templates.md': await templatesPage(),
  }
}

const generated = await pages()
let stale = false
mkdirSync(out, { recursive: true })
for (const [name, content] of Object.entries(generated)) {
  const path = join(out, name)
  let current = ''
  try {
    current = readFileSync(path, 'utf8')
  } catch {
    // Not written yet.
  }
  if (check) {
    if (current !== content) {
      console.error(`${relative(root, path)} is out of date: run \`pnpm docs:gen\`.`)
      stale = true
    }
  } else {
    writeFileSync(path, content)
    console.log(`Wrote ${relative(root, path)}`)
  }
}
process.exit(stale ? 1 : 0)
